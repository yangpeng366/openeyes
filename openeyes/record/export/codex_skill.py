"""Export a trajectory as a Codex SKILL.md (YAML front-matter + body).

Codex skills (and OpenAI / Claude skills) look like:

    ---
    name: my-skill
    description: One-line description shown to the LLM.
    ---

    # When to use
    ...

So we emit that header followed by:
- High-level intent
- Element action table (sourced from structured element schema)
- Step-by-step instructions

A pure text LLM can read this and decide when/how to call the skill.
"""
from __future__ import annotations

from ..event import Trajectory


def to_codex_skill(traj: Trajectory, *, description: str = "", model_hint: str = "") -> str:
    """Render a Codex SKILL.md from one trajectory.

    `description` should be a one-liner that an LLM will see at trigger time.
    `model_hint` lets you say which models can consume this (text-only).
    """
    if not description:
        # Auto-derive from trajectory name + first step's intent
        description = f"Replay the {traj.name} workflow on {traj.app_name or 'the active app'}."
    if not model_hint:
        model_hint = "text-only LLM friendly (no vision required)"

    name = "openeyes-record-" + (traj.name or "workflow").lower().replace(" ", "-")
    lines: list[str] = []
    lines.append("---")
    lines.append(f"name: \"{name}\"")
    lines.append(f"description: \"{description}\"")
    lines.append(f"model_hint: \"{model_hint}\"")
    lines.append("---")
    lines.append("")
    lines.append(f"# {traj.name}")
    lines.append("")
    if traj.description:
        lines.append(traj.description)
        lines.append("")
    lines.append("This skill was generated by OpenEyes Record. It replays a pre-recorded")
    lines.append("desktop workflow on the live application. All selectors are derived from")
    lines.append("structured accessibility data (UIA / CDP), so a pure text LLM can drive")
    lines.append("the workflow without any vision model.")
    lines.append("")
    lines.append("## Inputs")
    lines.append("")
    lines.append("None. The skill binds to the live window matching `app_name` and")
    lines.append("replays the recorded sequence.")
    lines.append("")
    lines.append("## Steps")
    lines.append("")
    lines.append("| # | Action | Target | Intent |")
    lines.append("|---|---|---|---|")
    for i, step in enumerate(traj.steps, 1):
        if hasattr(step, "element"):
            ed = step.element
            name = (ed.get("name") or "").replace("|", "\\|").strip()
            ctype = (ed.get("control_type") or "").strip()
            sel = getattr(step, "selector", "")
            intent = getattr(step, "intent", "") or ""
            act = step.action
            if act == "type":
                target = f"`{step.input_text or ''}` -> {ctype} \"{name}\""
            else:
                target = f"{ctype} \"{name}\" (`{sel}`)"
            lines.append(f"| {i} | `{act}` | {target} | {intent} |")
        else:
            # InputEvent
            act = step.action
            if act == "hotkey":
                lines.append(f"| {i} | `hotkey` | `{step.combo}` | {step.intent} |")
            elif act == "wait":
                lines.append(f"| {i} | `wait` | {step.duration_ms} ms | {step.intent} |")
            else:
                lines.append(f"| {i} | `{act}` | - | {step.intent} |")
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    lines.append("- Selectors prefer `automation_id` over `name + control_type` over `hint` over `bbox center`.")
    lines.append("- When a selector fails to resolve, the replayer falls back to the original bbox center.")
    lines.append("- All steps are safe to dry-run (`Replayer(dry_run=True).replay(traj)`).")
    lines.append("")
    return "\n".join(lines)